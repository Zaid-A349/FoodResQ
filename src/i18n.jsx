const LanguageContext = createContext(null)

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('frm_lang') || 'en')

  useEffect(() => {
    localStorage.setItem('frm_lang', lang)
    document.documentElement.lang = lang
  }, [lang])

  const toggle = useCallback(() => setLang((l) => (l === 'en' ? 'hi' : 'en')), [])
  const t = useCallback((key) => dict[lang][key] ?? dict.en[key] ?? key, [lang])

  return <LanguageContext.Provider value={{ lang, toggle, t }}>{children}</LanguageContext.Provider>
}

export function useLang() {
  return useContext(LanguageContext)
}
